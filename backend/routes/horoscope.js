// GET /api/horoscope/:sign — гороскоп на тиждень
router.get('/:sign', (req, res) => {
  const sign = req.params.sign?.toLowerCase();
  const data = WEEKLY[sign];
  if (!data) return res.status(404).json({ ok: false, error: 'Unknown sign' });

  // Дата поточного тижня
  const now   = new Date();
  const day   = now.getDay();
  const mon   = new Date(now); mon.setDate(now.getDate() - (day === 0 ? 6 : day - 1));
  const sun   = new Date(mon); sun.setDate(mon.getDate() + 6);
  const fmt   = d => d.toLocaleDateString('ru-RU', { day: 'numeric', month: 'long' });
  const period = `${fmt(mon)} — ${fmt(sun)}`;

  res.json({ ok: true, sign, period, data });
});

// GET /api/horoscope — список всіх знаків
router.get('/', (req, res) => {
  const signs = Object.entries(WEEKLY).map(([key, d]) => ({
    key, emoji: d.emoji, name: d.name, dates: d.dates,
  }));
  res.json({ ok: true, signs });
});


import { storage } from './platform.js';

let lang = 'en';
const LOCALES = { en: 'en-US', ru: 'ru-RU', ua: 'uk-UA' };

export function initLang() {
  const saved = storage.get('lunara_lang');
  // За замовчуванням завжди англійська; RU/UA — лише якщо юзер сам обрав
  lang = D[saved] ? saved : 'en';
  document.documentElement.lang = lang === 'ua' ? 'uk' : lang;
}
export const getLang = () => lang;
export const locale = () => LOCALES[lang];
export function setLang(l) {
  if (!D[l]) return;
  lang = l;
  storage.set('lunara_lang', l);
  document.documentElement.lang = l === 'ua' ? 'uk' : l;
}

export function t(key, vars) {
  let v = D[lang]?.[key] ?? D.en[key];
  if (v == null) return key;
  if (typeof v === 'function') return v(vars || {});
  if (typeof v !== 'string') return v;
  if (vars) v = v.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
  return v;
}

// Плюрали для RU/UA: 1 карта, 3 карты, 6 карт
const plural = (n, one, few, many) => {
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
};

